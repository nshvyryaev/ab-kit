/**
 * Сравнение двух долей и оценка размера выборки. Нормальное приближение —
 * его хватает на тех выборках, ради которых эксперимент вообще имеет смысл
 * (десятки событий в каждом варианте); на меньших отчёт и так покажет
 * интервал шире самой разницы.
 */

/**
 * Функция распределения стандартного нормального. Приближение erf по
 * Абрамовицу и Стигану (7.1.26): ошибка меньше 1,5·10⁻⁷ — на три знака
 * p-значения с большим запасом.
 */
export function normalCdf(z) {
  const x = Math.abs(z) / Math.SQRT2;
  const t = 1 / (1 + 0.3275911 * x);
  const poly = t * (0.254829592 + t * (-0.284496736 + t * (1.421413741 + t * (-1.453152027 + t * 1.061405429))));
  const erf = 1 - poly * Math.exp(-x * x);
  return z >= 0 ? (1 + erf) / 2 : (1 - erf) / 2;
}

/**
 * Квантиль стандартного нормального (алгоритм Акклама, относительная ошибка
 * порядка 10⁻⁹). Нужен для произвольных α и мощности в sampleSize.
 */
export function normalQuantile(p) {
  if (!(p > 0 && p < 1)) throw new Error('ab-kit: квантиль определён на (0, 1)');
  const a = [-39.69683028665376, 220.9460984245205, -275.9285104469687, 138.357751867269, -30.66479806614716, 2.506628277459239];
  const b = [-54.47609879822406, 161.5858368580409, -155.6989798598866, 66.80131188771972, -13.28068155288572];
  const c = [-0.007784894002430293, -0.3223964580411365, -2.400758277161838, -2.549732539343734, 4.374664141464968, 2.938163982698783];
  const d = [0.007784695709041462, 0.3224671290700398, 2.445134137142996, 3.754408661907416];
  const low = 0.02425;
  if (p < low) {
    const q = Math.sqrt(-2 * Math.log(p));
    return (((((c[0] * q + c[1]) * q + c[2]) * q + c[3]) * q + c[4]) * q + c[5]) / ((((d[0] * q + d[1]) * q + d[2]) * q + d[3]) * q + 1);
  }
  if (p > 1 - low) return -normalQuantile(1 - p);
  const q = p - 0.5;
  const r = q * q;
  return ((((((a[0] * r + a[1]) * r + a[2]) * r + a[3]) * r + a[4]) * r + a[5]) * q) /
    (((((b[0] * r + b[1]) * r + b[2]) * r + b[3]) * r + b[4]) * r + 1);
}

/**
 * Сравнение доли в варианте b с долей в варианте a (обычно a — контроль).
 *
 * Интервал разницы — по раздельным дисперсиям (Вальд); проверка гипотезы —
 * по объединённой доле, как принято в z-тесте двух долей. Разница
 * объяснима: при нулевой гипотезе доли равны, и общая оценка дисперсии
 * честнее, а интервал описывает разницу, какой она есть.
 */
export function compareProportions({ a, b, confidence = 0.95 }) {
  for (const [name, g] of [['a', a], ['b', b]]) {
    if (!g || !Number.isInteger(g.n) || !Number.isInteger(g.x) || g.n <= 0 || g.x < 0 || g.x > g.n) {
      throw new Error(`ab-kit: группа ${name} должна быть { n > 0, 0 ≤ x ≤ n } в целых`);
    }
  }
  const pa = a.x / a.n;
  const pb = b.x / b.n;
  const diff = pb - pa;
  const z95 = normalQuantile(1 - (1 - confidence) / 2);
  const se = Math.sqrt((pa * (1 - pa)) / a.n + (pb * (1 - pb)) / b.n);
  const pooled = (a.x + b.x) / (a.n + b.n);
  const se0 = Math.sqrt(pooled * (1 - pooled) * (1 / a.n + 1 / b.n));
  // Обе доли 0 или обе 1 — разницы нет и проверять нечего: z не определён.
  const z = se0 === 0 ? 0 : diff / se0;
  return {
    pa,
    pb,
    diff,
    lift: pa === 0 ? null : diff / pa,
    ci: [diff - z95 * se, diff + z95 * se],
    z,
    pValue: se0 === 0 ? 1 : 2 * (1 - normalCdf(Math.abs(z))),
  };
}

/**
 * Сколько единиц нужно в каждом варианте, чтобы заметить рост доли с `p` до
 * `p + mde` (mde — абсолютная разница, 0.05 значит «на 5 п. п.»).
 *
 *   n = (z₁₋α/₂ + z₁₋β)² · (p₁q₁ + p₂q₂) / mde²
 *
 * Формула по раздельным дисперсиям — та же, что для интервала в
 * compareProportions, поэтому оценка и отчёт говорят на одном языке.
 */
export function sampleSize({ p, mde, alpha = 0.05, power = 0.8 }) {
  const p2 = p + mde;
  if (!(p > 0 && p < 1 && p2 > 0 && p2 < 1 && mde !== 0)) {
    throw new Error('ab-kit: доли должны лежать в (0, 1), а разница — не ноль');
  }
  const z = normalQuantile(1 - alpha / 2) + normalQuantile(power);
  return Math.ceil((z * z * (p * (1 - p) + p2 * (1 - p2))) / (mde * mde));
}
